import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Repository root containing the core-generated contract and TypeScript output.
// 包含核心生成契约与 TypeScript 输出的仓库根目录。
const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
// Canonical contract copied byte-for-byte from the matching LuaSkills core release.
// 从匹配 LuaSkills 核心版本逐字节复制的规范契约。
const contractPath = join(
  repositoryRoot,
  "contracts",
  "skill-config",
  "v1",
  "contract.json",
);
// Generated TypeScript module consumed by the public SDK.
// 公共 SDK 使用的已生成 TypeScript 模块。
const outputPath = join(repositoryRoot, "src", "config-contract.ts");
// Parsed canonical contract used as the sole generation input.
// 作为唯一生成输入使用的已解析规范契约。
const contract = JSON.parse(readFileSync(contractPath, "utf8"));
// Deterministic source text expected for the current contract.
// 当前契约对应的确定性源码文本。
const generated = generateSource(contract);

if (process.argv.includes("--check")) {
  // Existing output compared without normalizing whitespace or line endings.
  // 不规范化空白或换行符而直接比较的现有输出。
  const existing = readFileSync(outputPath, "utf8");
  if (existing !== generated) {
    throw new Error(
      "src/config-contract.ts is stale; run npm run generate:config-contract",
    );
  }
} else {
  writeFileSync(outputPath, generated, "utf8");
}

/**
 * Render deterministic TypeScript constants from one canonical contract document.
 * 从一个规范契约文档渲染确定性 TypeScript 常量。
 *
 * @param {Record<string, any>} value Parsed canonical contract.
 * @returns {string} Complete generated TypeScript source.
 * @param value 已解析规范契约。
 * @returns 完整的已生成 TypeScript 源码。
 */
function generateSource(value) {
  // Declaration arrays retain the canonical order emitted by the core.
  // 声明数组保持核心生成的规范顺序。
  const types = value.declaration.types.map(quote).join(",\n  ");
  const formats = value.declaration.formats.map(quote).join(",\n  ");
  const states = value.declaration.states.map(quote).join(",\n  ");
  const describeModes = value.declaration.describe_modes.map(quote).join(",\n  ");
  const storeScopes = value.declaration.store_scopes.map(quote).join(",\n  ");
  // Stable error codes retain the canonical order emitted by the core.
  // 稳定错误码保持核心生成的规范顺序。
  const errors = value.errors.map(quote).join(",\n  ");
  return `// Code generated by scripts/generate-skill-config-contract.mjs; DO NOT EDIT.
// 此文件由 scripts/generate-skill-config-contract.mjs 生成；请勿手工编辑。

/**
 * Contract version emitted by the matching LuaSkills core release.
 * 与当前 SDK 匹配的 LuaSkills 核心版本所生成的契约版本。
 */
export const SKILL_CONFIG_CONTRACT_VERSION = ${value.contract_version} as const;

/**
 * Declared package-configuration scalar types.
 * 已声明技能包配置的标量类型。
 */
export const SKILL_PACKAGE_CONFIG_TYPES = [
  ${types},
] as const;

/**
 * Supported host rendering formats for string declarations.
 * 字符串声明支持的宿主渲染格式。
 */
export const SKILL_PACKAGE_CONFIG_FORMATS = [
  ${formats},
] as const;

/**
 * Stable effective-value states.
 * 稳定的有效值状态。
 */
export const SKILL_PACKAGE_CONFIG_STATES = [
  ${states},
] as const;

/**
 * Stable package-configuration declaration discovery modes.
 * 稳定的技能包配置声明发现模式。
 */
export const SKILL_PACKAGE_CONFIG_DESCRIBE_MODES = [
  ${describeModes},
] as const;

/**
 * Stable package-configuration declaration discovery mode.
 * 稳定的技能包配置声明发现模式。
 */
export type SkillPackageConfigDescribeMode =
  (typeof SKILL_PACKAGE_CONFIG_DESCRIBE_MODES)[number];

/**
 * Stable package-configuration store scopes.
 * 稳定的技能包配置存储作用域。
 */
export const SKILL_CONFIG_STORE_SCOPES = [
  ${storeScopes},
] as const;

/**
 * Stable package-configuration store scope.
 * 稳定的技能包配置存储作用域。
 */
export type SkillConfigStoreScope = (typeof SKILL_CONFIG_STORE_SCOPES)[number];

/**
 * Stable machine-readable package-configuration error codes.
 * 稳定的机器可读技能包配置错误码。
 */
export const SKILL_CONFIG_ERROR_CODES = [
  ${errors},
] as const;

/**
 * Stable machine-readable package-configuration error code.
 * 稳定的机器可读技能包配置错误码。
 */
export type SkillConfigErrorCode = (typeof SKILL_CONFIG_ERROR_CODES)[number];

/**
 * Largest exactly representable integer shared by every supported SDK.
 * 所有受支持 SDK 共同精确表示的最大整数。
 */
export const SKILL_CONFIG_MAXIMUM_SAFE_INTEGER = ${formatInteger(value.limits.maximum_safe_integer)};

/**
 * Largest event page accepted by the core contract.
 * 核心契约允许的最大事件分页大小。
 */
export const SKILL_CONFIG_MAXIMUM_EVENT_POLL_LIMIT = ${formatInteger(value.limits.maximum_event_poll_limit)};
`;
}

/**
 * Quote one canonical string as a JSON-compatible TypeScript literal.
 * 把一个规范字符串引用为 JSON 兼容的 TypeScript 字面量。
 *
 * @param {string} value Canonical string value.
 * @returns {string} Quoted literal.
 * @param value 规范字符串值。
 * @returns 引用后的字面量。
 */
function quote(value) {
  return JSON.stringify(value);
}

/**
 * Group one safe integer with underscores for generated source readability.
 * 使用下划线分组一个安全整数以提升生成源码可读性。
 *
 * @param {number} value Safe integer value.
 * @returns {string} Grouped decimal literal.
 * @param value 安全整数值。
 * @returns 分组后的十进制字面量。
 */
function formatInteger(value) {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, "_");
}
